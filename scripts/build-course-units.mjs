// Build the course → units table the site ships, from SSU's published Schedule
// of Classes. Run ONCE PER SEMESTER (the offering changes every term), then
// commit the result. See README "How to update this each semester".
//
//   node scripts/build-course-units.mjs data/F26_Schedule_of_Classes.pdf
//
// Input: the schedule as .pdf (needs `pdftotext` from poppler), .docx (macOS
// `textutil`), or already-extracted .txt (no tools needed — the portable path;
// on any OS you can open the file and "Save As / Export" plain text). Output:
// assets/course-units.js, stamped with the term from assets/config.js so the
// runtime can refuse a table that doesn't match the deployed term.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSchedule } from './parse-schedule.js';
import { config } from '../assets/config.js';

function extractText(file) {
  const ext = extname(file).toLowerCase();
  if (ext === '.txt') return readFileSync(file, 'utf8');
  if (ext === '.pdf') {
    try {
      return execFileSync('pdftotext', ['-layout', file, '-'], { encoding: 'utf8', maxBuffer: 64 << 20 });
    } catch {
      throw new Error('pdftotext (poppler) is required to read a .pdf. Install it, or export the schedule to .txt and pass that.');
    }
  }
  if (ext === '.docx' || ext === '.doc' || ext === '.rtf') {
    try {
      return execFileSync('textutil', ['-convert', 'txt', '-stdout', file], { encoding: 'utf8', maxBuffer: 64 << 20 });
    } catch {
      throw new Error('textutil (macOS) is required to read a .docx here. Export the schedule to .txt and pass that instead.');
    }
  }
  throw new Error(`Unsupported input "${ext}". Use .pdf, .docx, or .txt.`);
}

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/build-course-units.mjs <schedule.pdf|.docx|.txt>');
  process.exit(1);
}

const { units, stats } = parseSchedule(extractText(file));
if (stats.courses === 0) {
  console.error(`No courses parsed from ${file}. Is it really the Schedule of Classes text?`);
  process.exit(1);
}

// Sort keys so regenerating from the same input yields a byte-identical file
// (clean diffs; no spurious churn).
const sorted = Object.fromEntries(Object.keys(units).sort().map((k) => [k, units[k]]));
const body = Object.entries(sorted).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n');

const out = `// GENERATED by scripts/build-course-units.mjs — do NOT edit by hand.
// Source: ${basename(file)} (SSU Schedule of Classes). Regenerate every semester
// per the README; commit the result. Units for variable-unit courses are the
// rounded median of the values that course is offered at this term.
export const courseUnitsMeta = {
  term: ${JSON.stringify(config.term)},
  source: ${JSON.stringify(basename(file))},
  courses: ${stats.courses},
  variableCourses: ${stats.variableCourses},
};

export const courseUnits = {
${body}
};
`;

const outPath = fileURLToPath(new URL('../assets/course-units.js', import.meta.url));
writeFileSync(outPath, out);
console.log(`Wrote assets/course-units.js — ${stats.courses} courses (${stats.variableCourses} variable-unit), term "${config.term}", from ${basename(file)}.`);
